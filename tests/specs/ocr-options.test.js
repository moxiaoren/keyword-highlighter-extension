/** 去掉注释后的源码（按行保留换行与列位，行号不漂）—— 静态守卫不该打自己的解释性注释 */
function codeOf(rel) {
  return read(rel)
    .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '))
    .replace(/<!--[\s\S]*?-->/g, (m) => m.replace(/[^\n]/g, ' '))
    .replace(/\/\/[^\n]*/g, '');
}

